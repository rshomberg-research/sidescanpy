def _make_sonar_msg(
    *,
    ping_number: int = 0,
    channel: int = 0,
    timestamp_ns: int | None = None,
    transmit_freq_start: int = 1_495_000,
    transmit_freq_end: int = 1_495_000,
    sweep_length: float = 0.020,
    sample_freq: float = 400_000.0,
    n_samples: int = 100,
    backscatter_val: float = 1000.0,
    latitude: float = 41.0,
    longitude: float = -71.0,
    heading_deg: float = 90.0,
    depth_m: float = 12.0,
    roll_deg: float = 0.0,
    pitch_deg: float = 0.0,
    altitude_m: float = 5.0,
    sound_speed_ms: float = 1500.0,
) -> Mock:
    """Mock(spec=SonarDataMessage). Sonar messages use timestamp_ns (int)."""
    if timestamp_ns is None:
        timestamp_ns = _EPOCH_2026_NS + ping_number * 200_000_000

    m = Mock(spec=SonarDataMessage)
    m.ping_number       = ping_number
    m.channel           = channel
    m.timestamp_ns      = timestamp_ns
    m.transmit_freq_start = transmit_freq_start
    m.transmit_freq_end = transmit_freq_end
    m.sweep_length      = sweep_length
    m.sample_freq       = sample_freq
    m.N_samples         = n_samples
    m.backscatter_intensity = np.full(n_samples, backscatter_val, dtype=np.float32)

    m.latitude     = latitude
    m.longitude    = longitude
    m.heading_deg  = heading_deg
    m.depth_m      = depth_m
    m.roll_deg     = roll_deg
    m.pitch_deg    = pitch_deg
    m.altitude_m   = altitude_m
    m.sound_speed_ms = sound_speed_ms

    return m


